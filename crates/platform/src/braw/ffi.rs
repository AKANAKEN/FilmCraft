//! The part of the Blackmagic RAW API that FilmCraft calls, transcribed from the Linux
//! `BlackmagicRawAPI.h` and `LinuxCOM.h` of the Blackmagic RAW SDK 6.0.
//!
//! The interfaces are COM-style C++ classes that each derive directly from `IUnknown`, so an object
//! is a pointer to its vtable, and the vtable holds `QueryInterface`, `AddRef`, `Release` and then
//! the interface's methods in declaration order (Itanium C++ ABI). Each one ends with a protected
//! virtual destructor, whose two vtable entries come after every method. Slots FilmCraft never calls
//! are [`Slot`]s, kept so that the slots after them are at their right offsets (checked by the
