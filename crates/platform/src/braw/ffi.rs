/// `struct SafeArray` (only ever handled behind a pointer).
#[repr(C)]
pub struct SafeArray {
    _private: [u8; 0],
}

/// `struct Variant`: a type tag and an 8-byte union.
#[repr(C)]
pub struct Variant {
    pub vt: u32,
    pub value: VariantValue,
}

#[repr(C)]
#[derive(Clone, Copy)]
pub union VariantValue {
    pub i_val: i16,
    pub ui_val: u16,
    pub int_val: i32,
    pub uint_val: u32,
    pub flt_val: f32,
    pub dbl_val: f64,
    pub bstr_val: BrawString,
    pub parray: *mut SafeArray,
}

/// An interface pointer's target: the object starts with its vtable pointer.
#[repr(C)]
pub struct Object<V> {
    pub vtbl: *const V,
}

pub type This = *mut c_void;

#[repr(C)]
pub struct IUnknownVtbl {
    pub query_interface: unsafe extern "system" fn(This, Iid, *mut *mut c_void) -> Hresult,
    pub add_ref: unsafe extern "system" fn(This) -> Ulong,
    pub release: unsafe extern "system" fn(This) -> Ulong,
}

