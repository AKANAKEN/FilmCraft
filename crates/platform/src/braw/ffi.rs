#![allow(non_upper_case_globals)]

use std::ffi::{c_char, c_ulong, c_void};

pub type Hresult = i32;
/// `ULONG` is `unsigned long`: 64 bits on Linux.
pub type Ulong = c_ulong;
/// Strings are UTF-8 `const char*` on Linux, owned by the API unless a call says otherwise.
pub type BrawString = *const c_char;
/// A vtable entry FilmCraft never calls.
pub type Slot = *const c_void;

pub const S_OK: Hresult = 0;
// LinuxCOM.h's values (not Windows'): E_NOINTERFACE is 0x80000004 there.
pub const E_NOINTERFACE: Hresult = 0x8000_0004_u32 as i32;

/// `REFIID`: the interface id's 16 bytes, passed by value on Linux.
#[repr(C)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Iid(pub [u8; 16]);

